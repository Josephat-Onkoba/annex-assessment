#include <iostream>
#include <vector>
#include <string>
#include <algorithm>
#include <curl/curl.h>          // Used for making HTTP/API requests
#include <nlohmann/json.hpp>    // Used for parsing JSON

using namespace std;
using json = nlohmann::json;

//////////////////////////////////////////////////////////////
// STEP 1: CREATE A STRUCT
//
// This is our custom "blueprint" for storing article data.
//
// Instead of keeping the entire JSON object,
// we only store the fields we actually need:
//
// 1. article name
// 2. number of comments
//////////////////////////////////////////////////////////////
struct Article {
    string name;
    int num_comments;
};

//////////////////////////////////////////////////////////////
// STEP 2: CREATE A FUNCTION TO STORE API RESPONSE
//
// libcurl receives API data in chunks.
// This function helps append those chunks into a string.
//
// Think of it like:
//
// "Whenever new text arrives from the API,
// add it into our response string."
//////////////////////////////////////////////////////////////
size_t WriteCallback(void* contents, size_t size, size_t nmemb, string* output) {

    // size * nmemb = total bytes received
    size_t totalSize = size * nmemb;

    // Append received data into output string
    output->append((char*)contents, totalSize);

    return totalSize;
}

//////////////////////////////////////////////////////////////
// STEP 3: FUNCTION TO FETCH DATA FROM API
//
// This function:
// 1. Opens connection
// 2. Visits URL
// 3. Downloads response
// 4. Returns response as a string
//////////////////////////////////////////////////////////////
string fetchAPI(string url) {

    CURL* curl;
    CURLcode res;

    // This string will hold the API response
    string response;

    // Initialize curl
    curl = curl_easy_init();

    // Make sure curl initialized properly
    if (curl) {

        //////////////////////////////////////////////////////////
        // CURLOPT_URL
        //
        // Tells curl which URL to visit
        //////////////////////////////////////////////////////////
        curl_easy_setopt(curl, CURLOPT_URL, url.c_str());

        //////////////////////////////////////////////////////////
        // CURLOPT_WRITEFUNCTION
        //
        // Tells curl WHICH FUNCTION should handle incoming data
        //////////////////////////////////////////////////////////
        curl_easy_setopt(curl, CURLOPT_WRITEFUNCTION, WriteCallback);

        //////////////////////////////////////////////////////////
        // CURLOPT_WRITEDATA
        //
        // Tells curl WHERE to store the downloaded data
        //////////////////////////////////////////////////////////
        curl_easy_setopt(curl, CURLOPT_WRITEDATA, &response);

        //////////////////////////////////////////////////////////
        // Execute the request
        //////////////////////////////////////////////////////////
        res = curl_easy_perform(curl);

        //////////////////////////////////////////////////////////
        // Cleanup memory after request finishes
        //////////////////////////////////////////////////////////
        curl_easy_cleanup(curl);
    }

    return response;
}

//////////////////////////////////////////////////////////////
// STEP 4: CUSTOM SORTING FUNCTION
//
// This function tells std::sort HOW to rank articles.
//////////////////////////////////////////////////////////////
bool compareArticles(const Article& a, const Article& b) {

    //////////////////////////////////////////////////////////
    // PRIMARY SORT:
    // Higher num_comments comes first
    //////////////////////////////////////////////////////////
    if (a.num_comments != b.num_comments) {
        return a.num_comments > b.num_comments;
    }

    //////////////////////////////////////////////////////////
    // SECONDARY SORT:
    // If comments are tied,
    // sort article names in descending alphabetical order
    //
    // Example:
    // Zoo before Apple
    //////////////////////////////////////////////////////////
    return a.name > b.name;
}

//////////////////////////////////////////////////////////////
// MAIN FUNCTION
//////////////////////////////////////////////////////////////
vector<string> topArticles(int limit) {

    //////////////////////////////////////////////////////////
    // This vector stores ALL processed articles
    //////////////////////////////////////////////////////////
    vector<Article> all_articles;

    //////////////////////////////////////////////////////////
    // We don't know total pages yet.
    // We'll discover it after first API call.
    //////////////////////////////////////////////////////////
    int total_pages = 1;

    //////////////////////////////////////////////////////////
    // Start from page 1
    //////////////////////////////////////////////////////////
    int current_page = 1;

    //////////////////////////////////////////////////////////
    // LOOP THROUGH ALL PAGES
    //////////////////////////////////////////////////////////
    while (current_page <= total_pages) {

        //////////////////////////////////////////////////////
        // BUILD THE API URL
        //////////////////////////////////////////////////////
        string url =
            "https://jsonmock.hackerrank.com/api/articles?page="
            + to_string(current_page);

        //////////////////////////////////////////////////////
        // FETCH RAW JSON STRING
        //////////////////////////////////////////////////////
        string response = fetchAPI(url);

        //////////////////////////////////////////////////////
        // CONVERT RAW STRING INTO JSON OBJECT
        //////////////////////////////////////////////////////
        json j = json::parse(response);

        //////////////////////////////////////////////////////
        // GET TOTAL NUMBER OF PAGES
        //////////////////////////////////////////////////////
        total_pages = j["total_pages"];

        //////////////////////////////////////////////////////
        // ACCESS THE "data" ARRAY
        //////////////////////////////////////////////////////
        for (auto& item : j["data"]) {

            //////////////////////////////////////////////////
            // This variable will hold final article name
            //////////////////////////////////////////////////
            string final_name = "";

            //////////////////////////////////////////////////
            // RULE 1:
            // If title exists and is not null,
            // use title
            //////////////////////////////////////////////////
            if (!item["title"].is_null()) {

                final_name = item["title"];

            }

            //////////////////////////////////////////////////
            // RULE 2:
            // Otherwise use story_title
            //////////////////////////////////////////////////
            else if (!item["story_title"].is_null()) {

                final_name = item["story_title"];

            }

            //////////////////////////////////////////////////
            // RULE 3:
            // If BOTH are null,
            // skip this article completely
            //////////////////////////////////////////////////
            else {
                continue;
            }

            //////////////////////////////////////////////////
            // HANDLE num_comments
            //
            // If null -> treat as 0
            //////////////////////////////////////////////////
            int comments = 0;

            if (!item["num_comments"].is_null()) {
                comments = item["num_comments"];
            }

            //////////////////////////////////////////////////
            // CREATE ARTICLE OBJECT
            //////////////////////////////////////////////////
            Article article;

            article.name = final_name;
            article.num_comments = comments;

            //////////////////////////////////////////////////
            // SAVE ARTICLE INTO VECTOR
            //////////////////////////////////////////////////
            all_articles.push_back(article);
        }

        //////////////////////////////////////////////////////
        // MOVE TO NEXT PAGE
        //////////////////////////////////////////////////////
        current_page++;
    }

    //////////////////////////////////////////////////////////
    // SORT ALL ARTICLES
    //////////////////////////////////////////////////////////
    sort(all_articles.begin(), all_articles.end(), compareArticles);

    //////////////////////////////////////////////////////////
    // FINAL RESULT VECTOR
    //
    // This will store ONLY article names
    //////////////////////////////////////////////////////////
    vector<string> result;

    //////////////////////////////////////////////////////////
    // Prevent going out of bounds
    //////////////////////////////////////////////////////////
    int items_to_get = min(limit, (int)all_articles.size());

    //////////////////////////////////////////////////////////
    // TAKE TOP ARTICLES
    //////////////////////////////////////////////////////////
    for (int i = 0; i < items_to_get; i++) {

        result.push_back(all_articles[i].name);
    }

    //////////////////////////////////////////////////////////
    // RETURN FINAL ANSWER
    //////////////////////////////////////////////////////////
    return result;
}